/** Translate display text; protocol identifiers and stored robot state stay unchanged. */
export function t(text: string): string {
  const key = text.trim();
  const translated = language.value === "en" ? english[key] : undefined;
  if (translated !== undefined) return text.replace(key, translated);
  return text;
}

/** Translate template fragments while preserving numbers and other interpolated data. */
export function tr(parts: TemplateStringsArray, ...values: unknown[]): string {
  return parts.reduce((result, part, i) => result + t(part) + (i < values.length ? String(values[i]) : ""), "");
}

export function translateMessage(text: string): string {
  if (language.value === "ru") {
    const errors: Record<string, string> = {
      "ICE gathering timeout": "Истекло время ожидания ICE",
      "ICE connection failed": "Не удалось установить ICE соединение",
      "WHEP track timeout": "Истекло время ожидания видеопотока WHEP",
      "Unknown camera error": "Неизвестная ошибка камеры",
      "WebRTC failed": "Ошибка WebRTC соединения",
      "WebRTC disconnected": "WebRTC соединение разорвано",
      "Failed to fetch": "Не удалось получить данные",
      "Failed to load URDF": "Не удалось загрузить URDF",
    };
    return errors[text] ?? text.replace(/^WHEP POST failed: /, "Ошибка запроса WHEP: ");
  }
  if (english[text]) return english[text];
  if (text.startsWith("WS подключён: ")) return "WS connected: " + text.slice("WS подключён: ".length);
  return text.replace(/^(Планирование|Выполнение): Рука -> /, (_, scope: string) => t(scope) + ": Arm -> ");
}

function updateDocument() {
  document.documentElement.lang = language.value;
  document.title = t("РукаХод") + " · " + (language.value === "en" ? "Operator console" : "Пульт оператора");
}
export function setLanguage(next: Language) {
  language.value = next;
  try { localStorage.setItem(STORAGE_KEY, next); } catch { /* Private browsers may disallow storage. */ }
  updateDocument();
}
updateDocument();
